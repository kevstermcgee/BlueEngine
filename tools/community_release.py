#!/usr/bin/env python3
"""Publish an authored native game using the existing exact-source release gates."""
from __future__ import annotations

from datetime import datetime, timezone
from copy import deepcopy
import hashlib
import json
import os
from pathlib import Path
import re
import sys
from uuid import uuid4

try:
    from tools import idea_forge as forge
except ModuleNotFoundError:
    import idea_forge as forge


class Release(forge.Forge):
    """Reuse the same game, CI, installer, and public-download verification as IdeaForge."""

    def commit(self, root, message):
        super().commit(root, message.replace("generated by IdeaForge", "through the community workflow"))

    def validate_wiki(self, game):
        return forge.validate_game_wiki(game, allow_human=True)

    def update_native_definition(self, manifest, entry):
        entries = manifest["native_playables"]
        existing = next((item for item in entries if item["slug"] == entry["slug"]), None)
        if not existing or existing == entry:
            return super().update_native_definition(manifest, entry)
        structural = lambda item: {key: value for key, value in item.items() if key not in {"name", "binary"}}
        directory = Path("games") / self.state["idea"]["slug"]
        # Inspect the previous committed export receipt. The freshly regenerated
        # catalog cannot establish ownership of an existing companion definition.
        catalog = json.loads(forge.git(self.games, "show", "HEAD:.games-catalog.json"))
        managed = {item["path"] for item in catalog["files"]}
        preserved = [Path(value) for value in catalog.get("preserved_paths", [])]
        if (structural(existing) != structural(entry)
                or existing.get("directory") != directory.as_posix()
                or catalog.get("source_repository") != self.state["engine_repository"]
                or catalog.get("target_repository") != self.state["games_repository"]
                or not {(directory / "Cargo.toml").as_posix(), (directory / "game.project.json").as_posix()} <= managed
                or any(path == directory or path in directory.parents or directory in path.parents for path in preserved)):
            raise forge.ForgeError("Existing download definition lacks engine source ownership; preserve it and fork with a new slug")
        entries[entries.index(existing)] = entry
        return True

    def prepare(self):
        self.setup()
        game = self.game
        project = forge.load_json(game / "game.project.json")
        if project.get("id") != self.state["idea"]["slug"]:
            raise forge.ForgeError("game.project.json id must match the published game slug")
        identity = forge.load_json(game / "assets/identity.json")
        self.state["idea"]["title"] = identity["title"]
        wiki = self.validate_wiki(game)
        self.state["screenshot"] = str(game / wiki["gallery"][0]["image"])
        registry = self.engine / "games-publish.json"
        document = forge.load_json(registry)
        source = "games/" + self.state["idea"]["slug"]
        entries = document["collections"]["games"]
        # Existing games can have individually exported files or a whole-directory entry.
        if not any(entry["source"] == source or entry["source"].startswith(source + "/") for entry in entries):
            entries.append({"source": source, "destination": self.state["idea"]["slug"]})
            forge.atomic_json(registry, document)
        self.state["supervisor_files"] = {
            "games-publish.json": hashlib.sha256(registry.read_bytes()).hexdigest()}
        self.command([sys.executable, "scripts/publish_games.py", "check"], label="source-publication-check")
        forge.git(self.engine, "add", "--", "games-publish.json")
        self.commit(self.engine, "Register " + self.state["idea"]["title"] + " for native distribution")
        self.ensure_review_commit()
        self.state["engine_head"] = forge.git(self.engine, "rev-parse", "HEAD")
        self.state["verified_code"] = forge.code_digest(self.engine)

    def ensure_review_commit(self):
        # Intake intentionally skips CI for append-only events. A native review
        # needs a fresh push that actually runs CI, with identical authored code.
        message = forge.git(self.engine, "log", "-1", "--format=%B")
        if re.search(r"\[(?:skip ci|ci skip|no ci|skip actions|actions skip)\]|skip-checks:\s*true", message, re.I):
            self.state["source_review_base"] = forge.git(self.engine, "rev-parse", "HEAD")
            self.save()
            self.command(["git", "-c", "user.name=BlueEngine Community", "-c", "user.email=community@users.noreply.github.com",
                          "commit", "--allow-empty", "-m", "Review native source for " + self.state["idea"]["slug"]],
                         cwd=self.engine, label="native-source-review-commit")

    def assert_engine_gates(self):
        """Games metadata integration never authorizes different engine code."""
        if (forge.git(self.engine, "rev-parse", "HEAD") != self.state["engine_head"]
                or forge.code_digest(self.engine) != self.state["verified_code"]):
            raise forge.ForgeError("Engine source changed after verification; retain it for fresh source review")
        for label in ("engine-checks", "generated-game-linux-windows"):
            receipt = self.state.get("ci", {}).get(label, {})
            if receipt.get("head") != self.state["engine_head"]:
                raise forge.ForgeError("Missing exact engine source gate: " + label)
            run = self.api(f"repos/{self.state['engine_repository']}/actions/runs/{receipt['run']}")
            if (run.get("head_sha") != self.state["engine_head"]
                    or run.get("status") != "completed" or run.get("conclusion") != "success"):
                raise forge.ForgeError("The engine source gate is no longer successful: " + label)

    def games_snapshot(self, head):
        slug = self.state["idea"]["slug"]
        selected = "games/" + slug
        catalog = json.loads(forge.git(self.games, "show", head + ":.games-catalog.json"))
        if (catalog.get("source_repository") != self.state["engine_repository"]
                or catalog.get("target_repository") != self.state["games_repository"]
                or catalog.get("source_revision") != self.state["engine_head"]):
            raise forge.ForgeError("Concurrent Games export changed the pinned engine source; retain it for a fresh native release")
        definitions = json.loads(forge.git(self.games, "show", head + ":.release-games.json"))
        definitions = [item for item in definitions["native_playables"] if item.get("slug") == slug]
        if len(definitions) != 1:
            raise forge.ForgeError("The released game needs its unique native definition")
        return {"game_tree": forge.git(self.games, "rev-parse", head + ":" + selected),
                "definition": definitions[0],
                "thumbnail": forge.git(self.games, "rev-parse", head + ":site/thumbs/" + slug + ".png"),
                "ownership": sorted([item["path"], item["sha256"]] for item in catalog["files"]
                                    if item["path"] == selected or item["path"].startswith(selected + "/")),
                "preserved_paths": sorted(path for path in catalog.get("preserved_paths", [])
                                          if path == selected or path.startswith(selected + "/") or selected.startswith(path + "/"))}

    def publish_games(self):
        """Reconcile unrelated main updates and recheck the exact installer head."""
        self.assert_engine_gates()
        head = forge.git(self.games, "rev-parse", "HEAD")
        merge = Path(forge.git(self.games, "rev-parse", "--git-path", "MERGE_HEAD"))
        if not merge.is_absolute():
            merge = self.games / merge
        if merge.exists() or forge.git(self.games, "status", "--porcelain"):
            raise forge.ForgeError(f"Retained Games integration needs a clean committed merge in {self.games}; preserve the exact released game")
        recorded = self.state["games_head"]
        if head != recorded and not self.state.get("games_integration_pending"):
            raise forge.ForgeError("Games source changed outside its retained integration")
        frozen = self.state.setdefault("games_source_snapshot", self.games_snapshot(recorded))
        self.save()
        self.command(["git", "fetch", "origin", "main"], cwd=self.games, label="games-integration-fetch")
        # A confirmed original push remains valid when unrelated main commits
        # follow it; the original immutable production receipt remains the proof.
        if head == recorded and forge.git_ancestor(self.games, recorded, "origin/main"):
            if self.state.get("ci", {}).get("windows-installer-review", {}).get("head") != recorded:
                self.installer_review()
            self.assert_source_gates()
            return
        if not forge.git_ancestor(self.games, recorded, head):
            raise forge.ForgeError("Games integration lost the exact exported source commit")
        if not forge.git_ancestor(self.games, "origin/main", head):
            self.state["games_integration_pending"] = recorded
            self.save()
            self.command(["git", "-c", "user.name=BlueEngine Community", "-c", "user.email=community@users.noreply.github.com",
                          "merge", "--no-edit", "origin/main"], cwd=self.games, label="games-merge-main")
            head = forge.git(self.games, "rev-parse", "HEAD")
        if self.games_snapshot(head) != frozen:
            raise forge.ForgeError("Concurrent Games main changed the released game, thumbnail, ownership or native definition; retain its exact source for a separate reviewed release")
        if head != recorded:
            self.state.setdefault("games_verification_history", []).append({
                "head": recorded, "installer": deepcopy(self.state.get("ci", {}).get("windows-installer-review"))})
            self.state["games_head"] = head
            self.state.setdefault("ci", {}).pop("windows-installer-review", None)
        self.state.pop("games_integration_pending", None)
        self.save()
        if self.state.get("ci", {}).get("windows-installer-review", {}).get("head") != head:
            self.installer_review()
        self.assert_source_gates()
        self.command(["git", "fetch", "origin", "main"], cwd=self.games, label="games-publication-fetch")
        if forge.git_ancestor(self.games, head, "origin/main"):
            return
        if not forge.git_ancestor(self.games, "origin/main", head):
            raise forge.ForgeError("Games main advanced during installer review; resume to integrate and repeat its exact-source gate")
        self.command(["git", "push", "origin", head + ":main"], cwd=self.games, label="publish-games")

    def publish_source(self):
        self.assert_source_gates()
        source = self.state["engine_head"]
        integration = self.state.setdefault("feedback_integration", {
            "branch": self.state["branch"] + "-source", "source_head": source, "mode": "direct"})
        if integration["source_head"] != source:
            raise forge.ForgeError("Source integration no longer matches the immutable released source")
        self.save()
        self.command(["git", "fetch", "origin", "main"], label="source-main-fetch")
        direct = integration["mode"] == "direct" and (
            forge.git_ancestor(self.engine, "origin/main", source) or
            forge.git_ancestor(self.engine, source, "origin/main"))
        root, head = (self.engine, source) if direct else self.prepare_feedback_integration()
        if not direct:
            # The catalog already released this game's immutable tree. A concurrent
            # edit to that game needs a separate release, never a silently merged version.
            game = "games/" + self.state["idea"]["slug"]
            if forge.git(root, "rev-parse", source + ":" + game) != forge.git(root, "rev-parse", head + ":" + game):
                raise forge.ForgeError("Engine main changed the released game; preserve its exact tree in the retained source integration before resuming")
            branch = integration["branch"]
            self.command(["git", "push", "-u", "origin", head + ":refs/heads/" + branch],
                         cwd=root, label="push-source-integration")
            for workflow, label, dispatch in (
                    ("ci.yml", "source-integration-engine-" + head, False),
                    ("forge-game-checks.yml", "source-integration-native-" + head, True)):
                receipt = self.wait_ci(self.state["engine_repository"], workflow, branch, head, label,
                                       dispatch=dispatch, fields={"game_slug": self.state["idea"]["slug"]} if dispatch else None)
                if not receipt or receipt.get("head") != head:
                    raise forge.ForgeError("Source integration needs exact-commit engine and native CI")
        self.command(["git", "fetch", "origin", "main"], cwd=root, label="source-publication-fetch")
        if not forge.git_ancestor(root, head, "origin/main"):
            if not forge.git_ancestor(root, "origin/main", head):
                raise forge.ForgeError("Engine main advanced during source checks; resume to integrate and recheck")
            if forge.git(root, "rev-parse", "HEAD") != head or forge.git(root, "status", "--porcelain"):
                raise forge.ForgeError("Source integration changed after checks; retained without publication")
            self.command(["git", "push", "origin", head + ":main"], cwd=root, label="publish-source")
            self.command(["git", "fetch", "origin", "main"], cwd=root, label="source-confirmation-fetch")
            if not forge.git_ancestor(root, head, "origin/main"):
                raise forge.ForgeError("Source publication could not be confirmed on main; resume retains the checked commit")
        self.state["source_publication"] = {"commit": head, "released_source": source,
                                             "verified_at": datetime.now(timezone.utc).isoformat()}

    def advance(self):
        phases = (("prepare", self.prepare), ("local", self.verify_local),
                  ("engine_ci", self.engine_ci), ("export", self.export),
                  ("installer", self.installer_review), ("production", self.publish_games),
                  ("public_receipt", self.verify_publication), ("source", self.publish_source))
        for name, operation in phases:
            if name in self.state["completed"]:
                continue
            self.state["status"] = name
            self.save()
            operation()
            self.state["completed"].append(name)
            self.save()
        self.state["status"] = "published"
        self.save()
        return {"status": "published", "game": self.state["idea"]["slug"],
                "publication": self.state["publication"], "run": str(self.directory)}


def create(engine_root, games_root, slug, *, runs_root=None, wait_timeout=7200):
    engine_root, games_root = Path(engine_root).resolve(), Path(games_root).resolve()
    if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", slug):
        raise forge.ForgeError("Invalid game slug")
    if forge.git(engine_root, "status", "--porcelain", "--untracked-files=all"):
        raise forge.ForgeError("Commit source changes before release; the input checkout must be clean")
    if forge.github_repository(engine_root) != "kevstermcgee/BlueEngine":
        raise forge.ForgeError("Maintainer release needs the BlueEngine upstream origin; submit other forks as a publication PR")
    if forge.github_repository(games_root) != "kevstermcgee/BlueEngineGames":
        raise forge.ForgeError("--games-root must use the BlueEngineGames upstream origin")
    # Release an explicit local commit, never silently substitute an unrelated main revision.
    head = forge.git(engine_root, "rev-parse", "HEAD")
    directory = Path(runs_root or engine_root / ".be2-work/community/releases").resolve() / (
        datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S") + "-" + uuid4().hex[:8])
    directory.mkdir(parents=True, mode=0o700)
    target = Path(os.environ.get("CARGO_TARGET_DIR", engine_root / ".be2-work/community/cargo-target")).resolve()
    target.mkdir(parents=True, exist_ok=True)
    state = {"version": 1, "workflow": "community-release", "id": directory.name[-8:],
             "created": datetime.now(timezone.utc).isoformat(), "source_root": str(engine_root),
             "games_root": str(games_root), "base": head, "branch": "community-release/" + directory.name,
             "target_dir": str(target), "timeout": 7200, "wait_timeout": wait_timeout,
             "publish": True, "idea": {"slug": slug, "title": slug}, "completed": [], "status": "created"}
    release = Release(directory, state)
    release.save()
    return release


def run(engine_root, games_root, slug, **options):
    release = create(engine_root, games_root, slug, **options)
    return resume(release.directory)


def resume(directory):
    directory = Path(directory).resolve()
    with forge.run_lock(directory):
        state = forge.load_json(directory / "state.json")
        if state.get("workflow") != "community-release":
            raise forge.ForgeError("Not a community release journal")
        release = Release(directory, state)
        try:
            return release.advance()
        except (forge.ForgeError, OSError, ValueError, KeyError) as error:
            release.state["last_error"] = str(error)
            release.save()
            raise forge.ForgeError(f"Release retained at {directory}: {error}") from None
